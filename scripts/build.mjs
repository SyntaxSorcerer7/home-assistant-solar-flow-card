import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../', import.meta.url);
const sources = ['src/solar-flow-translations.js', 'src/solar-energy-flow.js', 'src/solar-flow-card.js'];
const bundle = '// Solar Flow Card v4.8.0 — generated by node scripts/build.mjs\n' +
  (await Promise.all(sources.map(path => readFile(new URL(path, root), 'utf8')))).join('\n');
await writeFile(new URL('solar-flow-card.js', root), bundle);
